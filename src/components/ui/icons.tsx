/**
 * Single source of truth for icons in this codebase.
 *
 * This barrel re-exports icons from @phosphor-icons/react under the
 * exact names the rest of the codebase expects (matching the old
 * lucide-react API). Renames are documented inline; icons that don't
 * have a 1:1 Lucide analog map to the closest Phosphor equivalent.
 *
 * Why this file exists:
 * - Phosphor ships 6 weights per icon. This barrel uses the default
 *   (regular) weight, which is what Lucide approximated.
 * - Per-icon deep imports tree-shake well; the alternative
 *   (`@phosphor-icons/react/dist/csr/<Name>`) is verbose and offers
 *   no measurable win in Next.js 16 with Turbopack. We pay ~6kb
 *   gzipped for the barrel overhead and get one-line imports.
 * - Adding `Bold` / `Duotone` variants later is trivial: append
 *   `as CheckBold` from the right per-icon file, then re-export here.
 *
 * When adding a new icon:
 * 1. Find the Phosphor name at https://phosphoricons.com
 * 2. Import it: `import { SomePhosphorName as NewIconAlias } from "@phosphor-icons/react"`
 * 3. Add the re-export below.
 */
